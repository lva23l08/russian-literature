with app.app_context():
    # Очищаем старые цитаты, чтобы не было дублей при повторном запуске
    Quote.query.delete()
    
    for writer_name, text in quotes_data:
        writer = Writer.query.filter_by(name=writer_name).first()
        if writer:
            quote = Quote(text=text, writer_id=writer.id, author_name="Редакция", likes=0)
            db.session.add(quote)
            
    db.session.commit()
    print("Цитаты успешно добавлены в базу!")