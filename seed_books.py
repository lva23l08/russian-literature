with app.app_context():
    # Очищаем старые книги, чтобы не было дублей
    Book.query.delete()
    
    for writer_name, books in books_data.items():
        writer = Writer.query.filter_by(name=writer_name).first()
        if writer:
            for title, year, plot in books:
                book = Book(title=title, year=year, plot=plot, cover="", writer_id=writer.id)
                db.session.add(book)
                
    db.session.commit()
